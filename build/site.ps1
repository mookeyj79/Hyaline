#requires -Version 7.0
<#
.SYNOPSIS
    Assembles the GitHub Pages site into _site/.

.DESCRIPTION
    The site mirrors the repo layout, so the relative paths in the published
    pages work the same on the site and in a checkout. It contains:

        what each port's site.json lists under "copy" (the preview port's
        dist/ and assets/), at its repo path
        each port's icon.svg, and the wallpapers
        one entry page per site.json "entries" item (/, /ports/), which
        opens that page in the visitor's OS variant
        _site/ports.js      the port list, from Ports/*/port.json and Ports/ports.json
        an install guide per listed port, its README.md rendered into the
        site.json "guide" page (dist/<variant>/guides/<port>.html), with an
        entry page at /Ports/<port>/ and the images the README shows

    In a guide, links to another port's README.md open that port's guide,
    links to other repo files open them on GitHub, and a link to a file
    that does not exist stops the build.

    The list is generated, never written by hand, so it cannot go stale.

    GitHub Pages lets browsers cache files for 10 minutes. So a deploy shows
    up on a normal reload, the copied pages load ports.js and their CSS with
    ?v=<content hash>, which changes whenever the file does.

    Stops if the port list or a site.json has errors; build/check.ps1 lists them.

.PARAMETER Out
    Output folder. Defaults to _site/ at the repo root.

.EXAMPLE
    pwsh build/site.ps1
    python3 -m http.server -d _site 8765    # then open http://127.0.0.1:8765/ports/
#>
[CmdletBinding()]
param(
    [string]$Out
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

Import-Module (Join-Path $PSScriptRoot 'lib' 'Palette.psm1') -Force
Import-Module (Join-Path $PSScriptRoot 'lib' 'Catalog.psm1') -Force

$RepoRoot  = Split-Path -Parent $PSScriptRoot
$PortsRoot = Join-Path $RepoRoot 'Ports'
if (-not $Out) { $Out = Join-Path $RepoRoot '_site' }
$Utf8 = [System.Text.UTF8Encoding]::new($false)

$palette = Read-Palette -Path (Join-Path $RepoRoot 'palette' 'palette.json')
if ($palette.Errors.Count -gt 0) { throw 'palette/palette.json has problems. Run build/check.ps1.' }
$name = [string]$palette.Meta['name']
$variants = @(Get-VariantKeys)

$catalog = Get-PortCatalog -PortsRoot $PortsRoot -VariantKeys $variants
$problems = @($catalog.Errors) + @($catalog.StructureErrors)
if ($problems.Count -gt 0) { throw "The port list has problems. Run build/check.ps1.`n" + ($problems -join "`n") }
$sites = @($catalog.Ports | Where-Object Site)
if ($sites.Count -ne 1) { throw "Exactly one port needs a site.json; found $($sites.Count)." }
$site = $sites[0]

# --- Copy the published port, icons, and wallpapers ---------------------------

if (Test-Path $Out) { Remove-Item -Path $Out -Recurse -Force }
$siteOut = Join-Path $Out 'Ports' $site.Name
New-Item -ItemType Directory -Path $siteOut -Force | Out-Null
foreach ($part in $site.Site['copy']) { Copy-Item -Path (Join-Path $site.Dir $part) -Destination $siteOut -Recurse }
Copy-Item -Path (Join-Path $RepoRoot 'wallpapers') -Destination $Out -Recurse
foreach ($p in $catalog.Ports | Where-Object Icon) {
    $iconOut = Join-Path $Out 'Ports' $p.Name
    New-Item -ItemType Directory -Path $iconOut -Force | Out-Null
    Copy-Item -Path (Join-Path $p.Dir 'icon.svg') -Destination $iconOut
}

# --- Port list ----------------------------------------------------------------

$data = ConvertTo-PortsData -Catalog $catalog
$json = ConvertTo-Json -InputObject $data -Depth 6 -Compress
$js = "// Generated by build/site.ps1 from Ports/*/port.json and Ports/ports.json.`nwindow.THEME_PORTS = $json;`n"
[System.IO.File]::WriteAllText((Join-Path $Out 'ports.js'), $js, $Utf8)

# --- Install guides -----------------------------------------------------------

$repo = ([string]$palette.Meta['repository']).TrimEnd('/')
$listedPorts = @($catalog.Ports | Where-Object Listed)
if (-not $site.Site['guide']) { throw "Ports/$($site.Name)/site.json needs 'guide', the page the install guides are built from." }
$listedNames = @($listedPorts | ForEach-Object Name)
$guideSpec = $site.Site['guide']
$guideDir = Split-Path -Parent $guideSpec
$guideShell = Split-Path -Leaf $guideSpec
# From a guide page back to the site root: guides/, <variant>/, dist/, <site port>/, Ports/.
$toRoot = '../' * (($guideSpec -split '/').Count + 3)

function Resolve-RepoPath([string]$FromDir, [string]$Target) {
    # A link target relative to a repo folder, as a repo path, or $null if it leaves the repo.
    $full = [System.IO.Path]::GetFullPath([System.IO.Path]::Combine($RepoRoot, $FromDir, [System.Uri]::UnescapeDataString($Target)))
    $rel = [System.IO.Path]::GetRelativePath($RepoRoot, $full) -replace '\\', '/'
    if ($rel -like '../*' -or $rel -eq '..') { return $null }
    return $rel
}

function ConvertTo-GuideHtml($Port) {
    $fromDir = "Ports/$($Port.Name)"
    $html = (ConvertFrom-Markdown -Path (Join-Path $Port.Dir 'README.md')).Html
    # Heading ids as GitHub makes them, so a #link works the same on both.
    $seen = @{}
    $html = [regex]::Replace($html, '<h(?<n>[1-6]) id="[^"]*">(?<text>.*?)</h\k<n>>', {
        param($m)
        $text = [System.Net.WebUtility]::HtmlDecode(($m.Groups['text'].Value -replace '<[^>]+>', ''))
        $id = ($text.ToLowerInvariant() -replace '[^\p{L}\p{Nd}\p{Mn}\p{Pc} -]', '') -replace ' ', '-'
        if ($seen.ContainsKey($id)) { $seen[$id]++; $id = "$id-$($seen[$id])" } else { $seen[$id] = 0 }
        "<h$($m.Groups['n'].Value) id=`"$id`">$($m.Groups['text'].Value)</h$($m.Groups['n'].Value)>"
    })
    return [regex]::Replace($html, '(?<attr>href|src)="(?<url>[^"]*)"', {
        param($m)
        $attr = $m.Groups['attr'].Value
        $url = [System.Net.WebUtility]::HtmlDecode($m.Groups['url'].Value)
        if ($url -eq '' -or $url -match '^(#|[a-z][a-z0-9+.-]*:|//)') { return $m.Value }
        $path, $hash = $url -split '#', 2
        $hash = if ($null -ne $hash) { "#$hash" } else { '' }
        $rel = Resolve-RepoPath $fromDir $path
        if (-not $rel -or -not (Test-Path (Join-Path $RepoRoot $rel))) {
            throw "$fromDir/README.md links to '$url', which is not a file in the repo."
        }
        if ($attr -eq 'href' -and $rel -match '^Ports/([^/]+)/README\.md$' -and $Matches[1] -in $listedNames) {
            $target = if ($Matches[1] -eq $Port.Name) { $hash } else { "$($Matches[1]).html$hash" }
            if (-not $target) { $target = '#' }
        }
        elseif ($attr -eq 'src') {
            # Images the guide shows are published at their repo path.
            $dest = Join-Path $Out $rel
            New-Item -ItemType Directory -Path (Split-Path -Parent $dest) -Force | Out-Null
            Copy-Item -Path (Join-Path $RepoRoot $rel) -Destination $dest -Force
            $target = $toRoot + (($rel -split '/' | ForEach-Object { [System.Uri]::EscapeDataString($_) }) -join '/')
        }
        else {
            $kind = if (Test-Path (Join-Path $RepoRoot $rel) -PathType Container) { 'tree' } else { 'blob' }
            $target = "$repo/$kind/main/" + (($rel -split '/' | ForEach-Object { [System.Uri]::EscapeDataString($_) }) -join '/') + $hash
        }
        return "$attr=`"$([System.Net.WebUtility]::HtmlEncode($target))`""
    })
}

foreach ($p in $listedPorts) {
    $body = ConvertTo-GuideHtml $p
    $title = [System.Net.WebUtility]::HtmlEncode("$name for $($p.Meta['name'])")
    $files = [System.Net.WebUtility]::HtmlEncode("$repo/tree/main/Ports/$($p.Name)/dist")
    $source = [System.Net.WebUtility]::HtmlEncode("$repo/blob/main/Ports/$($p.Name)/README.md")
    foreach ($v in $variants) {
        $shell = [System.IO.File]::ReadAllText((Join-Path $siteOut 'dist' $v $guideSpec))
        $page = $shell.Replace('<!-- guide:title -->', $title).Replace('<!-- guide:files -->', $files).
            Replace('<!-- guide:source -->', $source).Replace('<!-- guide:body -->', $body.TrimEnd())
        $page = $page -creplace '(href="[^"]*/)guide\.html"', "`$1$($p.Name).html`""
        [System.IO.File]::WriteAllText((Join-Path $siteOut 'dist' $v $guideDir "$($p.Name).html"), $page, $Utf8)
    }
}
foreach ($v in $variants) { Remove-Item -Path (Join-Path $siteOut 'dist' $v $guideSpec) }

# --- Cache busting ------------------------------------------------------------

function Get-ShortHash([string]$Path) {
    return (Get-FileHash -Path $Path -Algorithm SHA256).Hash.Substring(0, 10).ToLowerInvariant()
}

$portsJsHash = Get-ShortHash (Join-Path $Out 'ports.js')
foreach ($page in Get-ChildItem -Path $siteOut -Recurse -File -Filter '*.html') {
    $html = [System.IO.File]::ReadAllText($page.FullName)
    $html = $html -creplace '(src="[^"?]*/ports\.js)"', "`$1?v=$portsJsHash`""
    $html = [regex]::Replace($html, 'href="([^"?:]+\.css)"', {
        param($m)
        $target = Join-Path $page.DirectoryName $m.Groups[1].Value
        if (Test-Path $target) { 'href="' + $m.Groups[1].Value + '?v=' + (Get-ShortHash $target) + '"' }
        else { $m.Value }
    })
    [System.IO.File]::WriteAllText($page.FullName, $html, $Utf8)
}

# --- Entry pages that pick the visitor's variant ------------------------------

function Write-EntryPage([string]$Path, [string]$Title, [string]$Page) {
    # A page at $Path (relative to _site/) that opens $Page of the site port's
    # dist/<variant>/ in the visitor's OS variant, keeping the query and hash.
    $depth = ($Path -split '/').Count - 1
    $base = ('../' * $depth) + "Ports/$($site.Name)/dist/"
    $links = ($variants | ForEach-Object {
        $label = (Get-Culture).TextInfo.ToTitleCase($_)
        "<a href=`"$base$_/$Page`">$name $label</a>"
    }) -join ' / '
    $html = @"
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>$Title</title>
<meta http-equiv="refresh" content="0; url=$base$($variants[0])/$Page">
<script>
  var light = window.matchMedia && matchMedia("(prefers-color-scheme: light)").matches;
  location.replace("$base" + (light ? "light" : "dark") + "/$Page" + location.search + location.hash);
</script>
</head>
<body>$links</body>
</html>

"@
    $full = Join-Path $Out $Path
    New-Item -ItemType Directory -Path (Split-Path -Parent $full) -Force | Out-Null
    [System.IO.File]::WriteAllText($full, $html, $Utf8)
}

foreach ($entry in $site.Site['entries']) {
    Write-EntryPage -Path $entry['path'] -Title "$name $($entry['title'])" -Page $entry['page']
}
foreach ($p in $listedPorts) {
    Write-EntryPage -Path "Ports/$($p.Name)/index.html" -Title ([System.Net.WebUtility]::HtmlEncode("$name for $($p.Meta['name'])")) -Page "$guideDir/$($p.Name).html"
}

Write-Host "Site written to $Out ($($listedPorts.Count) port(s) with install guides, $(@($catalog.Planned).Count) planned)."
